"""Data-quality checks on the raw StatCan table and on the staples subset.

Writes outputs/data_quality.md (generated, numbers come from this run) and
outputs/dq_large_monthly_moves.csv.
"""
import csv
import io
from pathlib import Path

import pandas as pd

from clean import GEOS, RAW, ROOT, STAPLES, load_raw

META = ROOT / "data" / "raw" / "18100245_MetaData.csv"
OUT_MD = ROOT / "outputs" / "data_quality.md"
OUT_MOVES = ROOT / "outputs" / "dq_large_monthly_moves.csv"


def read_metadata(path: Path = META):
    """The metadata file is several CSV blocks stacked; return product notes + cube notes."""
    text = path.read_text(encoding="utf-8-sig")
    rows = list(csv.reader(io.StringIO(text)))
    product_notes, notes = {}, {}
    block = None
    for r in rows:
        if not r or not any(r):
            block = None
            continue
        if r[0] == "Dimension ID" and len(r) > 2 and r[2] == "Classification Code":
            block = "members"
            continue
        if r[0] == "Note ID":
            block = "notes"
            continue
        if block == "members" and r[0] == "2":
            product_notes[r[1].strip()] = r[6]
        elif block == "notes" and r[0].isdigit():
            notes[int(r[0])] = r[1]
    return product_notes, notes


def main() -> None:
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    raw = load_raw(RAW)
    raw_names = pd.read_csv(RAW, dtype=str, usecols=["Products"], encoding="utf-8-sig")["Products"]
    product_notes, notes = read_metadata()
    L = []  # markdown lines
    add = L.append

    add("# Data quality report (generated by `src/data_quality.py`)\n")
    add(f"Source file: `data/raw/18100245.csv`. Rows: **{len(raw):,}**; "
        f"months **{raw.REF_DATE.min()} to {raw.REF_DATE.max()}**; "
        f"{raw.GEO.nunique()} geographies; {raw.Products.nunique()} products.\n")

    # 1. Missing values
    add("## 1. Missing values\n")
    miss = raw[raw.VALUE.isna()]
    add(f"- Missing prices in the full table: **{len(miss)}** of {len(raw):,} rows "
        f"({len(miss) / len(raw):.3%}). Status symbols on those rows: "
        f"{miss.STATUS.fillna('(blank)').value_counts().to_dict()}.")
    by_geo = miss.groupby("GEO").size().to_dict()
    add(f"- Where: {by_geo}.")
    terr = raw[raw.GEO.str.contains("Yukon|Northwest")]
    add(f"- The two territorial capitals start in **{terr.REF_DATE.min()}** "
        f"(StatCan note 6: added with the September 2025 release; some products suppressed for confidentiality).")
    sub = raw[raw.GEO.isin(GEOS) & raw.Products.isin(STAPLES)]
    add(f"- In the analysed subset ({len(STAPLES)} staples x {len(GEOS)} geographies, all months): "
        f"**{sub.VALUE.isna().sum()} missing** values, months per series = "
        f"{sorted(sub.groupby(['GEO', 'Products']).size().unique().tolist())} "
        f"(expected {raw.REF_DATE.nunique()}), so no gaps.\n")

    # 2. Units and identifiers
    add("## 2. Units, scale and identifiers\n")
    add(f"- Unit of measure: {raw.UOM.unique().tolist()}; scalar factor: {raw.SCALAR_FACTOR.unique().tolist()}; "
        f"decimals: {sorted(raw.DECIMALS.unique().tolist())}. No unit or scale changes inside the table.")
    vec = raw.groupby(["GEO", "Products"]).VECTOR.nunique()
    add(f"- Vectors (series IDs) per geography x product: max **{vec.max()}**, so no series was re-coded mid-way. "
        f"`TERMINATED` flags: {int(raw.TERMINATED.notna().sum())}.")
    padded = sorted({n for n in raw_names.unique() if n != n.strip()})
    add(f"- **{len(padded)} product names have trailing spaces** in the raw file "
        f"(e.g. {', '.join(repr(n) for n in padded[:3])}). They are stripped in `clean.py`; "
        "otherwise exact-name filters and joins silently miss them.")
    add("- The package size is part of the product name (e.g. `Milk, 4 litres`), so the 'unit' of each "
        "price is the product definition itself. Different sizes of the same food are separate series "
        "(milk 1 L / 2 L / 4 L; onions per kg vs 1.36 kg bag) and must not be mixed.\n")

    # 3. Product definitions
    add("## 3. Product definitions\n")
    add("StatCan defines each product either by a **specific size** (note 3, e.g. 1 dozen eggs, prices per kg) "
        "or by a **standardized size** (note 4: packages within a size range are rescaled, e.g. 400-800 g cheese "
        "-> 500 g). Notes attached to the staples used here:\n")
    add("| Product | Metadata note(s) | Meaning |")
    add("|---|---|---|")
    meaning = {"3": "specific size", "4": "standardized size", "3;4": "both notes attached"}
    for p in STAPLES:
        n = product_notes.get(p, "?")
        add(f"| {p} | {n} | {meaning.get(n, n)} |")
    add("")
    add("Standardized products (cheese, bacon, coffee, pasta, bread, etc.) mix brands and package sizes, so a change in the "
        "mix that shoppers buy can move the average price even when no shelf price changed. "
        "The cube-level note 1 says it plainly: *average prices may not be fully comparable from one month to another "
        "and should not be used as a representative measure of pure price change*.\n")

    # 4. Series break, January 2024
    add("## 4. Series break: more retailers from January 2024\n")
    add("StatCan note 5: from the January 2024 reference month, data from **additional grocery retailers** were added. "
        "The 1-month change for January 2024 and 12-month changes during 2024 should be read with caution. "
        "Test on the staples subset (median absolute month-over-month change in January of each year):\n")
    s = sub.sort_values("REF_DATE").copy()
    s["mom_pct"] = s.groupby(["GEO", "Products"]).VALUE.pct_change() * 100
    jan = s[s.REF_DATE.str.endswith("-01") & s.mom_pct.notna()].copy()
    jan["year"] = jan.REF_DATE.str[:4]
    t = jan.groupby("year").mom_pct.agg(lambda x: x.abs().median()).round(2)
    allm = s.mom_pct.abs().median()
    add("| January of | median abs. m/m change (%) |")
    add("|---|---|")
    for y, v in t.items():
        add(f"| {y} | {v} |")
    add(f"\nFor reference, the median absolute m/m change over all months is **{allm:.2f}%**. "
        "A January 2024 value well above other Januaries would be the visible footprint of the break; "
        "see the table above for whether it shows up in these 20 staples.\n")

    # 5. Large monthly jumps
    add("## 5. Large month-over-month moves (possible outliers or composition shifts)\n")
    big = s[s.mom_pct.abs() >= 20][["REF_DATE", "GEO", "Products", "VALUE", "mom_pct"]]
    big = big.assign(mom_pct=big.mom_pct.round(1)).sort_values("mom_pct", key=abs, ascending=False)
    big.to_csv(OUT_MOVES, index=False)
    add(f"Moves of 20% or more in a single month in the staples subset (2017 onward): **{len(big)}** "
        f"of {s.mom_pct.notna().sum():,} monthly changes. Full list: `outputs/dq_large_monthly_moves.csv`. Largest:\n")
    add("| Month | Geography | Product | Price ($) | m/m % |")
    add("|---|---|---|---|---|")
    for r in big.head(10).itertuples():
        add(f"| {r.REF_DATE} | {r.GEO} | {r.Products} | {r.VALUE:.2f} | {r.mom_pct:+.1f} |")
    add("\nThese were **kept** (no evidence they are errors: produce is seasonal and smaller provinces have "
        "fewer transactions), but they are a reason to prefer 12-month averages over single-month comparisons.\n")

    # 6. Repeated values
    s["same_as_prev"] = s.groupby(["GEO", "Products"]).VALUE.diff() == 0
    rep = s.groupby("Products").same_as_prev.mean().sort_values(ascending=False) * 100
    add("## 6. Unchanged values month to month\n")
    add(f"Share of months where the price is exactly equal to the previous month (to the cent): overall "
        f"**{s.same_as_prev.mean() * 100:.1f}%**; highest for {rep.index[0]} ({rep.iloc[0]:.1f}%). "
        "Low values are expected for scanner-data averages; a high share would suggest carried-forward (imputed) values.\n")

    # 7. Provinces that move together
    add("## 7. Neighbouring provinces are not independent\n")
    w = raw[raw.Products.isin(STAPLES)].pivot_table(index=["Products", "REF_DATE"], columns="GEO", values="VALUE")
    pairs = [("Alberta", "Saskatchewan"), ("Nova Scotia", "New Brunswick"),
             ("Quebec", "Ontario"), ("Ontario", "Alberta"), ("Quebec", "Canada")]
    add("Median absolute gap between two geographies' average prices for the same staple and month (2017 onward):\n")
    add("| Pair | median abs. gap (%) | months within 1% |")
    add("|---|---|---|")
    for a, b in pairs:
        gap = ((w[a] - w[b]).abs() / w[b] * 100)
        add(f"| {a} vs {b} | {gap.median():.2f} | {(gap <= 1).mean() * 100:.0f}% |")
    add("\nNeighbouring provinces (Prairies, Maritimes) track each other much more "
        "closely than Quebec vs Ontario. The table cannot say why (shared regional pricing by grocery chains is one plausible reason, not verified here). "
        "Practical consequence: Alberta and Saskatchewan are **not two independent data points**, so agreement "
        "between them is not treated as extra evidence.\n")

    # 8. Revisions
    stamp = (ROOT / "data" / "raw" / "DOWNLOADED_AT.txt")
    when = stamp.read_text().split()[1] if stamp.exists() else "unknown"
    add("## 8. Revisions and comparability\n")
    add(f"- Data are subject to revision (note 1). This run used the file downloaded at **{when}** (UTC); "
        "re-running `src/download.py --force` may change recent months slightly.")
    add("- StatCan advises caution when comparing **across provinces** (brand/quality mix differs) and recommends the "
        "**CPI** for pure price change. This project therefore talks about *average prices paid*, not inflation in the CPI sense.")

    OUT_MD.write_text("\n".join(L) + "\n")
    print(f"Wrote {OUT_MD.relative_to(ROOT)} and {OUT_MOVES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
